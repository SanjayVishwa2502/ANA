import hashlib
import json
import uuid
from datetime import datetime, timezone
from typing import Dict, Any, Tuple, Optional

from .hash_pipeline import generate_clinical_hash

class MockLedgerState:
    """
    Simulates an immutable, permissioned Hyperledger Fabric key-value state store.
    Records contain zero Protected Health Information (zero PHI); only metadata
    and SHA-256 cryptographic fingerprints are anchored to the state.
    """
    def __init__(self):
        self._ledger: Dict[str, Dict[str, Any]] = {}

    def commit_transaction(self, tx_id: str, payload: Dict[str, Any]):
        """Commits an immutable transaction payload to the ledger."""
        if tx_id in self._ledger:
            raise ValueError(f"Ledger collision: Transaction {tx_id} already finalized!")
        self._ledger[tx_id] = payload
        print(f"[Ledger Commit Success] ⛓️ TxID: {tx_id} | Anchored Hash: {payload['sha256_hash'][:16]}...")

    def get_transaction(self, tx_id: str) -> Optional[Dict[str, Any]]:
        """Retrieves finalized transaction record by TxID."""
        return self._ledger.get(tx_id)

    def total_transactions(self) -> int:
        return len(self._ledger)


_global_ledger = MockLedgerState()

def get_shared_ledger() -> MockLedgerState:
    """Returns singleton instance of permissioned mock ledger."""
    global _global_ledger
    return _global_ledger


def generate_hash(data_dict: Dict[str, Any]) -> str:
    """Deterministic JSON SHA-256 hash generation."""
    return generate_clinical_hash(data_dict)


def anchor_note_to_ledger(
    dart_note: Dict[str, Any],
    actor_id: str = "Nurse_Auth_8841",
    action_type: str = "DART_NOTE_APPROVED",
    ledger: Optional[MockLedgerState] = None
) -> Tuple[str, str]:
    """
    Anchors off-chain DART note to the immutable ledger:
    Computes SHA-256 fingerprint and writes strictly zero-PHI metadata.
    Returns (tx_id, sha256_hash).
    """
    if ledger is None:
        ledger = get_shared_ledger()
        
    doc_hash = generate_clinical_hash(dart_note)
    tx_id = f"tx_{uuid.uuid4().hex[:12]}"
    
    payload = {
        "tx_id": tx_id,
        "actor_id": actor_id,
        "action_type": action_type,
        "timestamp_utc": datetime.now(timezone.utc).isoformat(),
        "sha256_hash": doc_hash,
        "status": "FINALIZED"
    }
    
    ledger.commit_transaction(tx_id, payload)
    return tx_id, doc_hash


def verify_offchain_integrity(
    tx_id: str,
    current_note: Dict[str, Any],
    ledger: Optional[MockLedgerState] = None
) -> Dict[str, Any]:
    """
    Recomputes SHA-256 hash from off-chain document and verifies against on-chain anchor.
    Detects any unauthorized tampering or silent data corruption post-approval.
    """
    if ledger is None:
        ledger = get_shared_ledger()
        
    tx_record = ledger.get_transaction(tx_id)
    if not tx_record:
        return {
            "verified": False,
            "error": f"Transaction {tx_id} not found in blockchain ledger."
        }
        
    on_chain_hash = tx_record["sha256_hash"]
    recomputed_hash = generate_clinical_hash(current_note)
    matches = (on_chain_hash == recomputed_hash)
    
    return {
        "verified": matches,
        "tx_id": tx_id,
        "on_chain_hash": on_chain_hash,
        "recomputed_hash": recomputed_hash,
        "tamper_detected": not matches
    }


def run_ledger_tamper_test():
    """Demonstrates full tamper-detection workflow as required by Review 3 rubrics."""
    print("==================================================================")
    print("🛡️ TIER 5: LEDGER AUDIT & TAMPER DETECTION VERIFICATION DEMO")
    print("==================================================================\n")
    
    ledger = MockLedgerState()
    
    # 1. Authentic DART Note generated by Tier 2
    authentic_note = {
        "data": ["Acutely diaphoretic and tachypneic", "Vitals: Sinus tachycardia at 135 bpm, BP 165/95"],
        "action": ["Administered 0.4 mg sublingual nitroglycerin", "Started 2 L oxygen via nasal cannula"],
        "response": ["Initial evaluation logged"],
        "teaching": ["Patient advised to remain still"],
        "confidence_score": 0.96,
        "requires_manual_flag": False
    }
    
    # Commit to ledger
    print("1. Anchoring Authentic DART Note Hash to Immutable Ledger...")
    tx_id, authentic_hash = anchor_note_to_ledger(authentic_note, ledger=ledger)
    print(f"   Anchored TxID: {tx_id} | Hash: {authentic_hash[:20]}...\n")
    
    # 2. Verification pass on unmodified note
    print("2. Verifying Unmodified Off-Chain Note...")
    check1 = verify_offchain_integrity(tx_id, authentic_note, ledger=ledger)
    if check1["verified"]:
        print("   ✅ INTEGRITY VERIFIED: Off-chain note matches on-chain fingerprint exactly!")
    else:
        print("   🚨 UNEXPECTED MISMATCH!")
        
    # 3. Simulate unauthorized data tampering (dosage altered: 0.4 mg -> 4.0 mg)
    print("\n3. Simulating Unauthorized Modification in Off-Chain Clinical Record...")
    tampered_note = json.loads(json.dumps(authentic_note))
    tampered_note["action"][0] = "Administered 4.0 mg sublingual nitroglycerin"  # Lethal 10x overdose!
    
    print(f"   Original Action: {authentic_note['action'][0]}")
    print(f"   Tampered Action: {tampered_note['action'][0]}")
    
    # 4. Verification on tampered record
    print("\n4. Running Cryptographic Verification on Tampered Note...")
    check2 = verify_offchain_integrity(tx_id, tampered_note, ledger=ledger)
    print(f"   On-Chain Anchored Hash : {check2['on_chain_hash']}")
    print(f"   Recomputed Tampered Hash: {check2['recomputed_hash']}")
    
    if check2["tamper_detected"]:
        print("   🚨 SECURITY ALERT DETECTED: Cryptographic hash mismatch!")
        print("   ✅ Tamper-Evidence System successfully isolated off-chain corruption post-approval!")
    else:
        print("   ⚠️ Tamper failed to detect change.")

if __name__ == "__main__":
    run_ledger_tamper_test()
